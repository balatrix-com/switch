#!/usr/bin/env python3
"""One-shot, bounded cleanup of expired FreeSWITCH recording files.

Run on the host containing RECORDINGS_DIRECTORY, once daily via systemd timer.
Billing records and wallet transactions are never deleted.
"""

from __future__ import annotations

import argparse
import logging
import os
import re
import stat
from collections import Counter
from contextlib import closing
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

import psycopg2


LOG = logging.getLogger("recording-cleanup")
RECORDING_PATH = re.compile(r"^([A-Za-z0-9-]{1,64})/([A-Za-z0-9-]{1,128})\.mp3$")
BATCH_SIZE = 100


def load_local_env() -> None:
    """Permit the existing service .env for manual runs; systemd can inject env."""
    if os.environ.get("DATABASE_URL") and os.environ.get("RECORDINGS_DIRECTORY"):
        return
    env_file = Path(__file__).with_name(".env")
    if not env_file.is_file():
        return
    for raw_line in env_file.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key in {"DATABASE_URL", "RECORDINGS_DIRECTORY"}:
            os.environ.setdefault(key, value.strip().strip('"').strip("'"))


def postgres_dsn(database_url: str) -> str:
    """Remove Prisma's schema URL parameter, which psycopg2 cannot use."""
    parsed = urlparse(database_url)
    query = [(key, value) for key, value in parse_qsl(parsed.query, keep_blank_values=True) if key != "schema"]
    return urlunparse(parsed._replace(query=urlencode(query)))


def validated_name(customer_id: str, relative_path: str) -> tuple[str, str]:
    """Allow only the exact customer/UUID.mp3 layout generated by the switch."""
    match = RECORDING_PATH.fullmatch(relative_path)
    if not match or match.group(1) != customer_id:
        raise ValueError("recording path does not match its customer and expected MP3 layout")
    return match.group(1), f"{match.group(2)}.mp3"


def delete_recording(root: Path, customer_id: str, relative_path: str) -> tuple[str, int]:
    """Unlink only a regular MP3 below the configured root, without following links."""
    customer_dir, filename = validated_name(customer_id, relative_path)
    directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    root_fd = os.open(root, directory_flags)
    try:
        try:
            customer_fd = os.open(customer_dir, directory_flags, dir_fd=root_fd)
        except FileNotFoundError:
            return "MISSING", 0
        try:
            try:
                details = os.stat(filename, dir_fd=customer_fd, follow_symlinks=False)
            except FileNotFoundError:
                return "MISSING", 0
            if not stat.S_ISREG(details.st_mode):
                raise ValueError("recording path is not a regular file")
            try:
                os.unlink(filename, dir_fd=customer_fd)
            except FileNotFoundError:
                return "MISSING", 0
            return "DELETED", details.st_size
        finally:
            os.close(customer_fd)
    finally:
        os.close(root_fd)


def pending_query() -> str:
    return """
        FROM rec
        WHERE expiry IS NOT NULL
          AND expiry < (NOW() AT TIME ZONE 'UTC')::date
          AND rec_file_info IS NOT NULL
          AND purge_status IN ('PENDING', 'ERROR')
          AND (purge_attempted_at IS NULL OR purge_attempted_at < %s)
    """


def cleanup(connection, root: Path, *, max_files: int = 50000, dry_run: bool = False) -> Counter:
    if max_files < 1:
        raise ValueError("max_files must be positive")
    root = root.resolve(strict=True)
    if root == Path("/") or not root.is_dir():
        raise ValueError("RECORDINGS_DIRECTORY must be an existing, specific directory")
    started_at = datetime.now(timezone.utc)
    counts: Counter = Counter()

    if dry_run:
        with connection.cursor() as cursor:
            cursor.execute(
                "SELECT id, cust_id, rec_file_info, expiry " + pending_query()
                + " ORDER BY expiry, id LIMIT %s",
                (started_at, min(max_files, 20)),
            )
            for row in cursor.fetchall():
                LOG.info("would check rec=%s customer=%s expiry=%s path=%s", *row)
                counts["SAMPLED"] += 1
        connection.rollback()
        return counts

    attempted = 0
    while attempted < max_files:
        remaining = min(BATCH_SIZE, max_files - attempted)
        with connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    "SELECT id, cust_id, rec_file_info " + pending_query()
                    + " ORDER BY expiry, id LIMIT %s FOR UPDATE SKIP LOCKED",
                    (started_at, remaining),
                )
                rows = cursor.fetchall()
                if not rows:
                    break
                for recording_id, customer_id, relative_path in rows:
                    status, file_bytes, error = "ERROR", 0, None
                    try:
                        status, file_bytes = delete_recording(root, customer_id, relative_path)
                    except (OSError, ValueError) as exc:
                        error = str(exc)[:1000]
                        LOG.error("rec=%s path=%s: %s", recording_id, relative_path, error)
                    cursor.execute(
                        """
                        UPDATE rec SET purge_status = %s,
                            purged_at = CASE WHEN %s IN ('DELETED', 'MISSING') THEN NOW() ELSE NULL END,
                            purge_attempted_at = %s, purge_attempts = purge_attempts + 1,
                            purge_error = %s, purged_bytes = %s
                        WHERE id = %s
                        """,
                        (status, status, started_at, error, file_bytes, recording_id),
                    )
                    attempted += 1
                    counts[status] += 1
                    counts["bytes_freed"] += file_bytes
    if attempted == max_files:
        with connection.cursor() as cursor:
            cursor.execute(
                "SELECT 1 " + pending_query() + " LIMIT 1",
                (started_at,),
            )
            if cursor.fetchone() is not None:
                counts["BACKLOG"] = 1
                LOG.warning("max-files limit reached; eligible recordings remain for another run")
        connection.rollback()
    return counts


def main() -> int:
    parser = argparse.ArgumentParser(description="Delete expired, tracked recording MP3s")
    parser.add_argument("--dry-run", action="store_true", help="show up to 20 eligible rows without deleting")
    parser.add_argument("--max-files", type=int, default=50000, help="maximum files attempted in one run")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s [%(name)s] %(message)s")
    load_local_env()
    database_url = os.environ.get("DATABASE_URL")
    directory = os.environ.get("RECORDINGS_DIRECTORY")
    if not database_url or not directory:
        parser.error("DATABASE_URL and RECORDINGS_DIRECTORY are required")
    with closing(psycopg2.connect(postgres_dsn(database_url))) as connection:
        counts = cleanup(connection, Path(directory), max_files=args.max_files, dry_run=args.dry_run)
    LOG.info(
        "complete deleted=%s missing=%s errors=%s bytes_freed=%s sampled=%s backlog=%s",
        counts["DELETED"], counts["MISSING"], counts["ERROR"],
        counts["bytes_freed"], counts["SAMPLED"], counts["BACKLOG"],
    )
    return 1 if counts["ERROR"] or counts["BACKLOG"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
