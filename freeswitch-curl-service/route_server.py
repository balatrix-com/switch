#!/usr/bin/env python3
"""FreeSWITCH xml_curl reader for persisted billing-switch DID XML files.

This service does not build routes or XML. It identifies the inbound carrier,
applies its configured ingress normalization profile, and reads the matching
XML file generated by the Node billing-switch backend.
"""

from __future__ import annotations

import json
import os
import sys
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from threading import Lock
from typing import Any
from urllib.parse import parse_qs, parse_qsl, urlencode, urlparse, urlunparse

import psycopg2.pool

from normalization import apply_steps


def load_env_file() -> None:
    """Load the colocated .env file without overriding process environment."""
    env_path = Path(__file__).with_name(".env")
    if not env_path.is_file():
        return
    for raw_line in env_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key and key.replace("_", "").isalnum():
            os.environ.setdefault(key, value.strip().strip('"').strip("'"))


load_env_file()

HOST = os.getenv("HOST", "0.0.0.0")
PORT = int(os.getenv("PORT", "8000"))
DATABASE_URL = os.environ["DATABASE_URL"]
XML_DIRECTORY = Path(os.getenv("XML_DIRECTORY", "./xml")).resolve()
CACHE_TTL_SECONDS = int(os.getenv("CACHE_TTL_SECONDS", "300"))
CACHE_FLUSH_TOKEN = os.getenv("CACHE_FLUSH_TOKEN", "change-me")

NOT_FOUND_XML = """<?xml version="1.0" encoding="UTF-8"?>
<document type="freeswitch/xml">
  <section name="result"><result status="not found"/></section>
</document>
"""


_CACHE_MISS = object()


class TtlCache:
    def __init__(self, ttl_seconds: int):
        self.ttl_seconds = ttl_seconds
        self.values: dict[str, tuple[Any, float]] = {}
        self.lock = Lock()

    def get(self, key: str) -> Any:
        with self.lock:
            item = self.values.get(key)
            if not item or item[1] <= time.time():
                self.values.pop(key, None)
                return _CACHE_MISS
            return item[0]

    def set(self, key: str, value: Any) -> None:
        with self.lock:
            self.values[key] = (value, time.time() + self.ttl_seconds)

    def clear(self) -> int:
        with self.lock:
            count = len(self.values)
            self.values.clear()
            return count

    def count(self) -> int:
        now = time.time()
        with self.lock:
            expired = [key for key, (_, expires) in self.values.items() if expires <= now]
            for key in expired:
                self.values.pop(key, None)
            return len(self.values)


def psycopg_dsn(database_url: str) -> str:
    """Remove Prisma-only URL options while preserving PostgreSQL options."""
    parsed = urlparse(database_url)
    query = dict(parse_qsl(parsed.query, keep_blank_values=True))
    query.pop("schema", None)
    return urlunparse(parsed._replace(query=urlencode(query)))


DB_POOL = psycopg2.pool.ThreadedConnectionPool(1, 10, dsn=psycopg_dsn(DATABASE_URL))
PROFILE_CACHE = TtlCache(CACHE_TTL_SECONDS)
ROUTE_CACHE = TtlCache(CACHE_TTL_SECONDS)


def source_identity(
    source_type: str,
    source_ip: str,
    source_port: int,
    auth_username: str | None,
) -> dict[str, str | None]:
    """Identify an active carrier or customer source and its ingress profile."""
    cache_key = f"source:{source_type}:{source_ip}:{source_port}:{auth_username or ''}"
    cached = PROFILE_CACHE.get(cache_key)
    if cached is not _CACHE_MISS:
        if cached is None:
            raise LookupError(f"{source_type.lower()} source is not authorized")
        return cached

    connection = DB_POOL.getconn()
    try:
        with connection.cursor() as cursor:
            if source_type == "CARRIER":
                cursor.execute(
                    """
                    SELECT NULL::text AS customer_id, COALESCE(
                        source.ingress_normalization_profile_id,
                        endpoint.ingress_normalization_profile_id,
                        carrier.default_ingress_profile_id
                    ) AS profile_id
                    FROM source_ip_auth AS source
                    JOIN carriers AS carrier ON carrier.id = source.carrier_id
                    LEFT JOIN carrier_endpoints AS endpoint
                        ON endpoint.id = source.carrier_endpoint_id
                    WHERE source.source_type = 'CARRIER'
                      AND source.is_active = TRUE
                      AND carrier.is_active = TRUE
                      AND source.ip_address = %s
                      AND (%s = 0 OR source.port = 0 OR source.port = %s)
                      AND (source.auth_username IS NULL OR source.auth_username = %s)
                    ORDER BY
                        CASE WHEN source.auth_username IS NULL THEN 1 ELSE 0 END,
                        CASE WHEN source.port = 0 THEN 1 ELSE 0 END
                    LIMIT 1
                    """,
                    (source_ip, source_port, source_port, auth_username),
                )
            elif source_type == "CUSTOMER":
                cursor.execute(
                    """
                    SELECT source.customer_id, COALESCE(
                        source.ingress_normalization_profile_id,
                        endpoint.ingress_normalization_profile_id,
                        settings.default_ingress_profile_id
                    ) AS profile_id
                    FROM source_ip_auth AS source
                    JOIN customers AS customer ON customer.id = source.customer_id
                    LEFT JOIN customer_endpoints AS endpoint
                        ON endpoint.id = source.customer_endpoint_id
                    LEFT JOIN customer_settings AS settings
                        ON settings.customer_id = customer.id
                    WHERE source.source_type = 'CUSTOMER'
                      AND source.is_active = TRUE
                      AND customer.is_active = TRUE
                      AND source.ip_address = %s
                      AND (%s = 0 OR source.port = 0 OR source.port = %s)
                      AND (source.auth_username IS NULL OR source.auth_username = %s)
                    ORDER BY
                        CASE WHEN source.auth_username IS NULL THEN 1 ELSE 0 END,
                        CASE WHEN source.port = 0 THEN 1 ELSE 0 END
                    LIMIT 1
                    """,
                    (source_ip, source_port, source_port, auth_username),
                )
            else:
                raise LookupError("unsupported source type")
            row = cursor.fetchone()
            if not row:
                PROFILE_CACHE.set(cache_key, None)
                raise LookupError(f"{source_type.lower()} source is not authorized")
            value = {
                "customer_id": str(row[0]) if row[0] else None,
                "profile_id": str(row[1]) if row[1] else None,
            }
            PROFILE_CACHE.set(cache_key, value)
            return value
    finally:
        DB_POOL.putconn(connection)


def profile_steps(profile_id: str | None) -> list[dict[str, Any]]:
    if not profile_id:
        return []
    cache_key = f"profile:{profile_id}"
    cached = PROFILE_CACHE.get(cache_key)
    if cached is not _CACHE_MISS:
        return cached

    connection = DB_POOL.getconn()
    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT steps
                FROM normalization_profiles
                WHERE id = %s AND is_active = TRUE
                """,
                (profile_id,),
            )
            row = cursor.fetchone()
            steps = row[0] if row and isinstance(row[0], list) else []
            PROFILE_CACHE.set(cache_key, steps)
            return steps
    finally:
        DB_POOL.putconn(connection)


def find_did_xml(normalized_number: str) -> dict[str, str] | None:
    """Resolve an active assigned DID by RouteXml.matchNumber.

    The saved file name is deliberately fetched from the database instead of
    being inferred from the dialled number. This keeps the Python service a
    read-only consumer of the configuration materialized by the Node backend.
    """
    cache_key = f"inbound:{normalized_number}"
    cached = ROUTE_CACHE.get(cache_key)
    if cached is not _CACHE_MISS:
        return cached

    connection = DB_POOL.getconn()
    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT route_xml.id, route_xml.file_name
                FROM route_xml
                JOIN customer_numbers
                  ON customer_numbers.id = route_xml.customer_number_id
                JOIN global_number_inventory
                  ON global_number_inventory.id = customer_numbers.inventory_id
                JOIN customers
                  ON customers.id = customer_numbers.customer_id
                WHERE route_xml.match_number = %s
                  AND route_xml.file_name IS NOT NULL
                  AND customer_numbers.status = 'ACTIVE'
                  AND global_number_inventory.status = 'ASSIGNED'
                  AND customers.is_active = TRUE
                LIMIT 1
                """,
                (normalized_number,),
            )
            row = cursor.fetchone()
            result = (
                {"id": str(row[0]), "file_name": str(row[1])} if row else None
            )
            ROUTE_CACHE.set(cache_key, result)
            return result
    finally:
        DB_POOL.putconn(connection)


def find_outbound_xml(
    customer_id: str, normalized_number: str
) -> dict[str, str] | None:
    """Resolve a pre-generated exact outbound route owned by the source customer."""
    cache_key = f"outbound:{customer_id}:{normalized_number}"
    cached = ROUTE_CACHE.get(cache_key)
    if cached is not _CACHE_MISS:
        return cached

    connection = DB_POOL.getconn()
    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT route_xml.id, route_xml.file_name
                FROM switch_routes AS route
                JOIN route_xml ON route_xml.route_id = route.id
                JOIN customers AS customer ON customer.id = route.customer_id
                WHERE route.customer_id = %s
                  AND route.direction = 'OUTBOUND'
                  AND route.match_type = 'EXACT'
                  AND route.match_value = %s
                  AND route.is_active = TRUE
                  AND customer.is_active = TRUE
                  AND route_xml.file_name IS NOT NULL
                LIMIT 1
                """,
                (customer_id, normalized_number),
            )
            row = cursor.fetchone()
            result = (
                {"id": str(row[0]), "file_name": str(row[1])} if row else None
            )
            ROUTE_CACHE.set(cache_key, result)
            return result
    finally:
        DB_POOL.putconn(connection)


def read_xml(file_name: str) -> str:
    path = (XML_DIRECTORY / file_name).resolve()
    if path.parent != XML_DIRECTORY:
        raise LookupError("invalid XML path")
    return path.read_text(encoding="utf-8")


class RouteHandler(BaseHTTPRequestHandler):
    def do_POST(self) -> None:
        parsed = urlparse(self.path)
        if parsed.path == "/admin/cache/flush":
            self.handle_cache_flush()
            return
        try:
            content_length = int(self.headers.get("Content-Length", "0"))
            body = self.rfile.read(content_length).decode("utf-8", errors="ignore")
            fields = parse_qs(body, keep_blank_values=True)
            fields.update(parse_qs(parsed.query, keep_blank_values=True))
            destination = self.first(fields, "Caller-Destination-Number", "destinationNumber")
            forwarded_source_ip = self.first(
                fields,
                "variable_sip_h_X-Source-IP",
                "sourceIp",
            )
            source_ip = forwarded_source_ip or self.first(
                fields, "variable_sip_network_ip"
            )
            forwarded_source_port = self.first(
                fields,
                "variable_sip_h_X-Source-Port",
                "sourcePort",
            )
            source_port = int(
                forwarded_source_port
                or (
                    self.first(fields, "variable_sip_network_port")
                    if not forwarded_source_ip
                    else "0"
                )
                or "0"
            )
            auth_username = self.first(
                fields, "variable_sip_auth_username", "authUsername"
            )
            direction = (
                self.first(fields, "variable_sip_h_X-Call-Direction", "direction")
                or "inbound"
            ).lower()
            if not destination or not source_ip:
                raise LookupError("destination number and source IP are required")

            if direction == "inbound":
                identity = source_identity(
                    "CARRIER", source_ip, source_port, auth_username
                )
                normalized = apply_steps(
                    destination, profile_steps(identity["profile_id"])
                )
                route = find_did_xml(normalized)
            elif direction == "outbound":
                identity = source_identity(
                    "CUSTOMER", source_ip, source_port, auth_username
                )
                normalized = apply_steps(
                    destination, profile_steps(identity["profile_id"])
                )
                if not identity["customer_id"]:
                    raise LookupError("customer source has no customer ID")
                route = find_outbound_xml(identity["customer_id"], normalized)
            else:
                raise LookupError("unsupported call direction")
            if not route:
                raise LookupError(f"no active {direction} route matches {normalized}")
            xml = read_xml(route["file_name"])
            print(
                f"[XML] source={source_ip}:{source_port} raw={destination} "
                f"normalized={normalized} route={route['id']} "
                f"file={route['file_name']}"
            )
            self.respond_xml(xml)
        except Exception as error:
            print(f"[XML] not-found: {error}")
            self.respond_xml(NOT_FOUND_XML)

    def do_GET(self) -> None:
        if urlparse(self.path).path == "/health":
            self.respond_json(
                200,
                {
                    "ok": True,
                    "service": "freeswitch-curl-service",
                    "xmlDirectory": str(XML_DIRECTORY),
                    "routeCacheCount": ROUTE_CACHE.count(),
                    "profileCacheCount": PROFILE_CACHE.count(),
                },
            )
            return
        self.respond_json(404, {"ok": False, "error": "not found"})

    def handle_cache_flush(self) -> None:
        if self.headers.get("X-Cache-Token", "") != CACHE_FLUSH_TOKEN:
            self.respond_json(403, {"ok": False, "error": "forbidden"})
            return
        cleared_profiles = PROFILE_CACHE.clear()
        cleared_routes = ROUTE_CACHE.clear()
        self.respond_json(
            200,
            {
                "ok": True,
                "cleared": cleared_profiles + cleared_routes,
                "profiles": cleared_profiles,
                "routes": cleared_routes,
            },
        )

    @staticmethod
    def first(fields: dict[str, list[str]], *names: str) -> str | None:
        for name in names:
            values = fields.get(name)
            if values:
                return values[0]
        return None

    def respond_xml(self, xml: str) -> None:
        payload = xml.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/xml; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def respond_json(self, status: int, value: dict[str, Any]) -> None:
        payload = json.dumps(value).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, _format: str, *_args: Any) -> None:
        return


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(line_buffering=True)
    XML_DIRECTORY.mkdir(parents=True, exist_ok=True)
    print(f"[XML-SERVER] listening on {HOST}:{PORT}")
    print(f"[XML-SERVER] reading persisted XML from {XML_DIRECTORY}")
    ThreadingHTTPServer((HOST, PORT), RouteHandler).serve_forever()
