def ensure_recording_directory(xml: str) -> None:
    """Create the tenant recording directory only for recording-enabled XML."""
    if "execute_on_answer=record_session " not in xml:
        return
    match = re.search(r"billing_customer_id=([A-Za-z0-9-]+)", xml)
    if not match:
        raise LookupError("recording XML has no billing_customer_id")
    customer_id = match.group(1)
    customer_directory = (RECORDINGS_DIRECTORY / customer_id).resolve()
    if customer_directory.parent != RECORDINGS_DIRECTORY:
        raise LookupError("invalid recording customer directory")
    customer_directory.mkdir(parents=True, exist_ok=True, mode=0o770)
    customer_directory.chmod(0o770)


def carrier_source_identity(
    source_ip: str,
    source_port: int,
    auth_username: str | None,
) -> dict[str, str | None]:
    """Find carrier identity and ingress normalization for the live source."""
    cache_key = f"carrier_source:{source_ip}:{source_port}:{auth_username or ''}"
    cached = PROFILE_CACHE.get(cache_key)
    if cached is not _CACHE_MISS:
        return cached

    connection = DB_POOL.getconn()
    try:
        with connection.cursor() as cursor:
            # 1. Check source_ip_auth + joined endpoint + joined carrier
            cursor.execute(
                """
                SELECT carrier.id,
                    COALESCE(source.carrier_endpoint_id, endpoint.id),
                    COALESCE(
                    source.ingress_normalization_profile_id,
                    endpoint.ingress_normalization_profile_id,
                    carrier.default_ingress_profile_id
                ) AS profile_id
                FROM source_ip_auth AS source
                JOIN carriers AS carrier ON carrier.id = source.carrier_id
                LEFT JOIN carrier_endpoints AS endpoint
                    ON (endpoint.id = source.carrier_endpoint_id OR (endpoint.carrier_id = carrier.id AND endpoint.host = source.ip_address))
                WHERE source.source_type = 'CARRIER'
                  AND source.is_active = TRUE
                  AND carrier.is_active = TRUE
                  AND source.ip_address = %s
                  AND (%s = 0 OR source.port = 0 OR source.port = %s)
                  AND (source.auth_username IS NULL OR source.auth_username = %s)
                ORDER BY
                    CASE WHEN source.ingress_normalization_profile_id IS NOT NULL THEN 0
                         WHEN endpoint.ingress_normalization_profile_id IS NOT NULL THEN 1
                         ELSE 2 END
                """,
                (source_ip, source_port, source_port, auth_username),
            )
            rows = cursor.fetchall()
            carrier_ids = {str(candidate[0]) for candidate in rows if candidate[0]}
            row = rows[0] if len(carrier_ids) == 1 else None
            if len(carrier_ids) > 1:
                print(
                    f"[XML] WARN ambiguous carrier source: src={source_ip}:{source_port} "
                    f"carriers={sorted(carrier_ids)}"
                )
            if row:
                identity = {
                    "carrier_id": str(row[0]),
                    "carrier_endpoint_id": str(row[1]) if row[1] else None,
                    "profile_id": str(row[2]) if row[2] else None,
                }
                PROFILE_CACHE.set(cache_key, identity)
                return identity

            # 2. Check carrier_endpoints directly by host
            cursor.execute(
                """
                SELECT carrier.id, endpoint.id, COALESCE(
                    endpoint.ingress_normalization_profile_id,
                    carrier.default_ingress_profile_id
                ) AS profile_id
                FROM carrier_endpoints AS endpoint
                JOIN carriers AS carrier ON carrier.id = endpoint.carrier_id
                WHERE endpoint.is_active = TRUE
                  AND carrier.is_active = TRUE
                  AND endpoint.host = %s
                  AND (%s = 0 OR endpoint.port = 0 OR endpoint.port = %s)
                ORDER BY
                    CASE WHEN endpoint.ingress_normalization_profile_id IS NOT NULL THEN 0 ELSE 1 END
                """,
                (source_ip, source_port, source_port),
            )
            rows = cursor.fetchall()
            carrier_ids = {str(candidate[0]) for candidate in rows if candidate[0]}
            row = rows[0] if len(carrier_ids) == 1 else None
            if len(carrier_ids) > 1:
                print(
                    f"[XML] WARN ambiguous carrier endpoint: src={source_ip}:{source_port} "
                    f"carriers={sorted(carrier_ids)}"
                )
            identity = (
                {
                    "carrier_id": str(row[0]),
                    "carrier_endpoint_id": str(row[1]),
                    "profile_id": str(row[2]) if row[2] else None,
                }
                if row
                else {
                    "carrier_id": None,
                    "carrier_endpoint_id": None,
                    "profile_id": None,
                }
            )
            PROFILE_CACHE.set(cache_key, identity)
            return identity
    finally:
        DB_POOL.putconn(connection)


